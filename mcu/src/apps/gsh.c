#include "apps/gsh.h"

// kernel
#include "kernel/gio.h"
#include "kernel/gstr.h"
#include "kernel/gsys.h"


//-----------------------------------------------------------------------------
//  GLOBAL VARIABLES
//-----------------------------------------------------------------------------

#define CMD_LEN     64

volatile char gsh_cmd[CMD_LEN];

volatile char cur_user[] = "gort";
volatile char cur_path[] = "/home/gort";


//-----------------------------------------------------------------------------
//  FUNCTIONS
//-----------------------------------------------------------------------------

/**
 * @brief The Gort Shell
 * 
 * @param none
 * 
 * @return process status
 */
int main_gsh(void)
{
    while(1)
    {
        helloworld(cur_user);
        helloworld("@");
        helloworld(cur_path);
        helloworld("$ ");

        hellogort(gsh_cmd, 0, '\r');
        // ----------------------------------------------------
        
        // print rtc time
        print_systime();

        // ----------------------------------------------------
        helloworld("\n");
    }
    
    return 0;
}
