/**
 * @brief main test
 * 
 * @return never!
 */
int main(void)
{
    WDTCTL = WDTPW | WDTHOLD; // stop watchdog timer

    PM5CTL0 &= ~LOCKLPM5; // turn off low-power mode

    // TEST CODE HERE -------------------------------------
    P1DIR |= BIT0;
    P1OUT &= ~BIT0;

    int i;
    while (1)
    {
        for (i = 0; i < 30000; i++) {}
        P1OUT ^= BIT0;
        
    } // halt / loop forever
    return 0;
    // ----------------------------------------------------
}
