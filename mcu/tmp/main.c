//-----------------------------------------------------------------------------
//  LIBRARIES
//-----------------------------------------------------------------------------

#include <msp430.h>


//-----------------------------------------------------------------------------
//  GLOBAL VARIABLES
//-----------------------------------------------------------------------------


//-----------------------------------------------------------------------------
//  FUNCTIONS
//-----------------------------------------------------------------------------

int main(void)
{
    WDTCTL = WDTPW | WDTHOLD; // Stop watchdog timer

    P1DIR |= BIT0;  // Configure LED1 as output
    P1OUT &= ~BIT0; // Turn off LED1

    PM5CTL0 &= ~LOCKLPM5; // Turn off low-power mode

    unsigned int i;
    while (1)
    {
        for (i = 0; i < 65535; i++) {} // Short delay

        P1OUT ^= BIT0; // Toggle LED1
    }
    return 0;
}
