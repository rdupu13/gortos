#include <msp430.h>

    .global main
    .text

;------------------------------------------------------------------------------
; START OF CODE
;------------------------------------------------------------------------------

main:
    mov.w #WDTPW|WDTHOLD, &WDTCTL

    bis.b #0x01, &P1DIR
    bic.b #0x01, &P1OUT

    bic.w #0x0001, &PM5CTL0

loop:
    mov.w #0xFFFF, R4
delay:
    nop
    nop
    nop
    dec.w R4
    jnz delay
            
    xor.b #0x01, &P1OUT

    jmp loop

    ret

;------------------------------------------------------------------------------
; END OF CODE
;------------------------------------------------------------------------------
